#!/usr/bin/env bash
# install.sh — provision one Pi as a surveillance-os camera node.
# Run on the Pi after flashing Raspberry Pi OS (64-bit) + first-boot setup:
#
#   curl -fsSL <repo>/deploy/install.sh | sudo bash -s -- --cam home-a --hub 100.x.y.z
#
# Assumes: Pi 4 + Camera Module 3, tailscaled already installed (or --tailscale-key
# to auth it), chrony, and gstreamer1.0 + libcamera packages.
set -euo pipefail

CAM_ID=""
HUB=""
TS_KEY=""
BIN_SRC="${BIN_SRC:-./agent}" # prebuilt linux/arm64 binary, or cross-compile below

while [ $# -gt 0 ]; do
  case "$1" in
    --cam) CAM_ID="$2"; shift 2 ;;
    --hub) HUB="$2"; shift 2 ;;
    --tailscale-key) TS_KEY="$2"; shift 2 ;;
    --bin) BIN_SRC="$2"; shift 2 ;;
    *) echo "unknown arg: $1" >&2; exit 1 ;;
  esac
done

[ -n "$CAM_ID" ] || { echo "--cam <cam_id> required (e.g. home-a)" >&2; exit 1; }
[ -n "$HUB" ] || { echo "--hub <host:port> required (hub tailnet IP)" >&2; exit 1; }

echo "==> installing surveillance agent: cam=$CAM_ID hub=$HUB"

# --- packages ----------------------------------------------------------------
apt-get update -qq
apt-get install -y --no-install-recommends \
  gstreamer1.0-tools gstreamer1.0-plugins-good gstreamer1.0-plugins-bad \
  rpicam-apps libcamera-ipa chrony curl
# tailscale: install if absent (https://tailscale.com/download/linux)
if ! command -v tailscaled >/dev/null; then
  curl -fsSL https://tailscale.com/install.sh | sh
fi

# --- camera enablement -------------------------------------------------------
# Camera Module 3 on Pi OS: ensure overlays + enough CMA for 1080p encode.
raspi-config nonint do_camera 0 2>/dev/null || true
if ! grep -q "^camera_auto_detect=1" /boot/firmware/config.txt 2>/dev/null; then
  echo "camera_auto_detect=1" >> /boot/firmware/config.txt
fi
# libcamera needs CMA for high-res capture; bump if the default is too small.
if ! grep -q "cma=" /boot/firmware/cmdline.txt 2>/dev/null; then
  sed -i 's/$/ cma=128M/' /boot/firmware/cmdline.txt
fi

# --- tailnet -----------------------------------------------------------------
if [ -n "$TS_KEY" ]; then
  # Node name doubles as the ingest identity: the hub whois-checks it.
  tailscale up --auth-key="$TS_KEY" --hostname="$CAM_ID" --ssh=false
else
  echo "==> skipping 'tailscale up' (no --tailscale-key); run it manually:"
  echo "      tailscale up --hostname=$CAM_ID"
fi

# --- binary + config ---------------------------------------------------------
install -d -m 0755 /opt/surveillance /etc/surveillance
if [ -f "$BIN_SRC" ]; then
  install -m 0755 "$BIN_SRC" /opt/surveillance/agent
else
  echo "!! no binary at $BIN_SRC — build one first:" >&2
  echo "     cd src/video-service && GOOS=linux GOARCH=arm64 go build -o agent ./cmd/agent" >&2
  echo "   then re-run with --bin ./agent" >&2
  exit 1
fi

cat > /etc/surveillance/agent.toml <<EOF
# generated by install.sh $(date -u +%F)
cam_id = "$CAM_ID"
hub    = "$HUB"

# source = "libcamerasrc"                  # default — real camera
# source = "videotestsrc is-live=true"     # smoke-test without a camera module
#   (also set software_encode = true when the host has no v4l2h264enc)

width   = 1920
height  = 1080
fps     = 10
bitrate = 700_000

thumbs       = true
spool_dir    = "/run/surveillance/spool"
spool_max_mb = 1024
EOF
chmod 0600 /etc/surveillance/agent.toml

# --- systemd -----------------------------------------------------------------
install -m 0644 "$(dirname "$0")/agent.service" /etc/systemd/system/surveillance-agent.service 2>/dev/null \
  || install -m 0644 agent.service /etc/systemd/system/surveillance-agent.service
systemctl daemon-reload
systemctl enable chrony tailscaled 2>/dev/null || true
systemctl enable --now surveillance-agent.service

# --- sanity checks ------------------------------------------------------------
echo "==> checks:"
echo "    camera:   rpicam-hello --list-cameras"
echo "    gst elem: gst-inspect-1.0 libcamerasrc | head -3   # must exist before first boot"
echo "    encoder:  v4l2-ctl -d /dev/video11 --list-ctrls | grep -E 'bitrate|gop'"
echo "    tailnet:  tailscale status"
echo "    agent:    journalctl -u surveillance-agent -f"
echo "==> done. The pipeline starts after reboot (or: systemctl start surveillance-agent)"
